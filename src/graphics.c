static bool canvas_is_valid(const gfx_canvas_t *canvas) {
  return canvas != NULL && canvas->buf != NULL && canvas->native_width > 0 &&
         canvas->native_height > 0 && canvas->stride_bytes > 0;
}

void gfx_clear(gfx_canvas_t *canvas) {
  if (!canvas_is_valid(canvas)) {
    return;
  }
  size_t buf_size = (size_t)canvas->stride_bytes * (size_t)canvas->native_height;
  memset(canvas->buf, 0xFF, buf_size);
}

void gfx_set_pixel(gfx_canvas_t *canvas, int x, int y, bool black) {
  if (!canvas_is_valid(canvas)) {
    return;
  }

  const int landscape_w = canvas->native_height;
  const int landscape_h = canvas->native_width;
  if (x < 0 || x >= landscape_w || y < 0 || y >= landscape_h) {
    return;
  }

  int nx;
  int ny;
  if (canvas->rotate_180) {
    nx = y;
    ny = (canvas->native_height - 1) - x;
  } else {
    nx = (canvas->native_width - 1) - y;
    ny = x;
  }

  size_t idx = (size_t)ny * (size_t)canvas->stride_bytes + (size_t)(nx >> 3);
  uint8_t mask = (uint8_t)(0x80 >> (nx & 7));

  if (black) {
    canvas->buf[idx] &= (uint8_t)~mask;
  } else {
    canvas->buf[idx] |= mask;
  }
}

void gfx_fill_rect(gfx_canvas_t *canvas, int x, int y, int w, int h,
                   bool black) {
  if (!canvas_is_valid(canvas)) {
    return;
  }
  for (int dy = 0; dy < h; dy++) {
    for (int dx = 0; dx < w; dx++) {
      gfx_set_pixel(canvas, x + dx, y + dy, black);
    }
  }
}

void gfx_draw_hline(gfx_canvas_t *canvas, int x, int y, int w, bool black) {
  gfx_fill_rect(canvas, x, y, w, 1, black);
}

enum {
  FONT_5X7_FIRST_CHAR = 0x20,
  FONT_5X7_LAST_CHAR = 0x7E,
  FONT_5X7_WIDTH = 5,
  FONT_5X7_HEIGHT = 7,
  FONT_5X7_ADVANCE = 6,

  SEG7_DIGIT_WIDTH = 44,
  SEG7_DIGIT_HEIGHT = 76,
  SEG7_THICKNESS = 8,
  SEG7_INSET = 2,
  SEG7_HALF_GAP = 1,
  SEG7_COLON_WIDTH = 14,
  SEG7_COLON_DOT_SIZE = 8,
  SEG7_COLON_X_OFFSET = 3,
  SEG7_COLON_TOP_Y = 20,
  SEG7_COLON_BOT_Y = 48,
  SEG7_DIGIT_GAP = 8,
};

static void gfx_draw_char(gfx_canvas_t *canvas, int x, int y, char c, int scale,
                          bool black) {
  unsigned char uc = (unsigned char)c;
  if (uc < FONT_5X7_FIRST_CHAR || uc > FONT_5X7_LAST_CHAR) {
    uc = '?';
  }
  const uint8_t *glyph = FONT_5X7[uc - FONT_5X7_FIRST_CHAR];
  for (int col = 0; col < FONT_5X7_WIDTH; col++) {
    uint8_t bits = glyph[col];
    for (int row = 0; row < FONT_5X7_HEIGHT; row++) {
      if (bits & (1u << row)) {
        gfx_fill_rect(canvas, x + col * scale, y + row * scale, scale, scale,
                      black);
      }
    }
  }
}

void gfx_draw_text(gfx_canvas_t *canvas, int x, int y, const char *str,
                   int scale, bool black) {
  if (!canvas_is_valid(canvas) || str == NULL || scale <= 0) {
    return;
  }
  int cx = x;
  int step = FONT_5X7_ADVANCE * scale;
  while (*str) {
    gfx_draw_char(canvas, cx, y, *str, scale, black);
    cx += step;
    str++;
  }
}

// 7-segment bitmask: bit 0=a(top), 1=b(top-right), 2=c(bot-right), 3=d(bot),
//                    4=e(bot-left), 5=f(top-left), 6=g(mid)
static const uint8_t SEG7_DIGITS[10] = {
    0x3F, // 0: a b c d e f
    0x06, // 1: b c
    0x5B, // 2: a b d e g
    0x4F, // 3: a b c d g
    0x66, // 4: b c f g
    0x6D, // 5: a c d f g
    0x7D, // 6: a c d e f g
    0x07, // 7: a b c
    0x7F, // 8: a b c d e f g
    0x6F, // 9: a b c d f g
};

static void draw_large_digit(gfx_canvas_t *canvas, int x, int y, int digit) {
  if (digit < 0 || digit > 9) {
    return;
  }
  const int w = SEG7_DIGIT_WIDTH;
  const int h = SEG7_DIGIT_HEIGHT;
  const int t = SEG7_THICKNESS;
  const int v_len = h / 2 - SEG7_INSET - SEG7_HALF_GAP;
  uint8_t seg = SEG7_DIGITS[digit];

  if (seg & 0x01) { // a: top
    gfx_fill_rect(canvas, x + SEG7_INSET, y, w - 2 * SEG7_INSET, t, true);
  }
  if (seg & 0x02) { // b: top-right
    gfx_fill_rect(canvas, x + w - t, y + SEG7_INSET, t, v_len, true);
  }
  if (seg & 0x04) { // c: bottom-right
    gfx_fill_rect(canvas, x + w - t, y + h / 2 + SEG7_HALF_GAP, t, v_len, true);
  }
  if (seg & 0x08) { // d: bottom
    gfx_fill_rect(canvas, x + SEG7_INSET, y + h - t, w - 2 * SEG7_INSET, t,
                  true);
  }
  if (seg & 0x10) { // e: bottom-left
    gfx_fill_rect(canvas, x, y + h / 2 + SEG7_HALF_GAP, t, v_len, true);
  }
  if (seg & 0x20) { // f: top-left
    gfx_fill_rect(canvas, x, y + SEG7_INSET, t, v_len, true);
  }
  if (seg & 0x40) { // g: middle
    gfx_fill_rect(canvas, x + SEG7_INSET, y + (h - t) / 2, w - 2 * SEG7_INSET,
                  t, true);
  }
}

static void draw_large_colon(gfx_canvas_t *canvas, int x, int y) {
  gfx_fill_rect(canvas, x + SEG7_COLON_X_OFFSET, y + SEG7_COLON_TOP_Y,
                SEG7_COLON_DOT_SIZE, SEG7_COLON_DOT_SIZE, true);
  gfx_fill_rect(canvas, x + SEG7_COLON_X_OFFSET, y + SEG7_COLON_BOT_Y,
                SEG7_COLON_DOT_SIZE, SEG7_COLON_DOT_SIZE, true);
}

void gfx_draw_large_time(gfx_canvas_t *canvas, int x, int y, int hour,
                         int min) {
  if (!canvas_is_valid(canvas)) {
    return;
  }

  int h1 = (hour / 10) % 10;
  int h2 = hour % 10;
  int m1 = (min / 10) % 10;
  int m2 = min % 10;

  int cx = x;
  draw_large_digit(canvas, cx, y, h1);
  cx += SEG7_DIGIT_WIDTH + SEG7_DIGIT_GAP;
  draw_large_digit(canvas, cx, y, h2);
  cx += SEG7_DIGIT_WIDTH + SEG7_DIGIT_GAP;
  draw_large_colon(canvas, cx, y);
  cx += SEG7_COLON_WIDTH + SEG7_DIGIT_GAP;
  draw_large_digit(canvas, cx, y, m1);
  cx += SEG7_DIGIT_WIDTH + SEG7_DIGIT_GAP;
  draw_large_digit(canvas, cx, y, m2);
}
